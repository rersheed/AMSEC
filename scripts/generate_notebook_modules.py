def segments(cell: int, names: list[str]) -> list[str]:
    src = cell_source(cell)
    tree = ast.parse(src)
    found = {n.name: ast.get_source_segment(src, n) for n in tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef))}
    missing = [n for n in names if n not in found]
    if missing:
        raise SystemExit(f"cell {cell}: missing definitions {missing}")
    return [found[n] for n in names]


def main() -> None:
    for filename, (cell, names, purpose) in SPEC.items():
        header = (
            f'"""AUTO-GENERATED by scripts/generate_notebook_modules.py — DO NOT EDIT.\n\n'
            f"{purpose}\n\nSource: notebooks/{NOTEBOOK_NAME} (sha256 {NOTEBOOK_SHA256[:16]}…), cell {cell}.\n"
            f"Definitions: {', '.join(names)}.\n"
            f'Bodies are byte-identical to the notebook; verified by tests/test_notebook_fidelity.py.\n"""\n'
            "# ruff: noqa\n# flake8: noqa\n"
        )
        body = IMPORTS if filename == "keras_common.py" else "from amsec.notebook.keras_common import *  # noqa: F401,F403\nfrom amsec.notebook.keras_common import keras, np, time, to_categorical  # explicit for readers\n"
        defs = "\n\n\n".join(segments(cell, names))
        (OUT / filename).write_text(header + body + "\n\n" + defs + "\n", encoding="utf-8")
        print(f"wrote {filename}: {names}")


if __name__ == "__main__":
    main()
